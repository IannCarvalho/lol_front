import json
import pymongo
import requests

def get_lore(champion):	
    url = f"https://ddragon.leagueoflegends.com/cdn/13.19.1/data/pt_BR/champion/{champion}.json"

    # Faz a solicitação GET à URL
    response = requests.get(url)

    # Verifica se a solicitação foi bem-sucedida (código de status 200)
    if response.status_code == 200:
        # O conteúdo da resposta é o JSON
        json_data = response.json()
        # Agora você pode trabalhar com o JSON
        return json_data["data"][champion]['lore']
    else:
        # Se a solicitação não foi bem-sucedida, você pode lidar com erros aqui
        print(f"Erro na solicitação: Código de status {response.status_code} no champion: {champion}")
        return "Completar"
		

